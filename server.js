/**
 * Lightweight Zero-Dependency Native HTTP Server
 * Distributed Computing Mini Project: Lamport Logical Clock Simulator
 */

const http = require('http');
const fs = require('fs');
const path = require('path');

const PORT = process.env.PORT || 3000;
const PUBLIC_DIR = path.join(__dirname, 'public');
const SRC_DIR = path.join(__dirname, 'src');

const MIME_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon',
  '.png': 'image/png'
};

const server = http.createServer((req, res) => {
  // Normalize URL
  const parsedUrl = new URL(req.url, `http://${req.headers.host || 'localhost'}`);
  let pathname = decodeURIComponent(parsedUrl.pathname);

  // Serve src/ files if requested
  let filePath;
  if (pathname.startsWith('/src/')) {
    filePath = path.join(__dirname, pathname);
  } else {
    if (pathname === '/') {
      pathname = '/index.html';
    }
    filePath = path.join(PUBLIC_DIR, pathname);
  }

  // Security check: stay within project directory
  if (!filePath.startsWith(__dirname)) {
    res.writeHead(403, { 'Content-Type': 'text/plain' });
    res.end('403 Forbidden');
    return;
  }

  fs.stat(filePath, (err, stats) => {
    if (err || !stats.isFile()) {
      res.writeHead(404, { 'Content-Type': 'text/plain' });
      res.end(`404 Not Found: ${pathname}`);
      return;
    }

    const ext = path.extname(filePath).toLowerCase();
    const contentType = MIME_TYPES[ext] || 'application/octet-stream';

    res.writeHead(200, {
      'Content-Type': contentType,
      'Cache-Control': 'no-cache, no-store, must-revalidate'
    });

    const stream = fs.createReadStream(filePath);
    stream.pipe(res);
  });
});

server.listen(PORT, () => {
  console.log(`\n======================================================`);
  console.log(`  LAMPORT LOGICAL CLOCK SIMULATOR - WEB DASHBOARD`);
  console.log(`  Server is running at: http://localhost:${PORT}`);
  console.log(`======================================================\n`);
  console.log(`Open http://localhost:${PORT} in your web browser to interact!`);
});
